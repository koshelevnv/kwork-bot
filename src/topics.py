def pack_title(pack_id: str) -> str:
    entry = TOPIC_PACKS.get(pack_id)
    return entry[0] if entry else pack_id


def pack_keywords(pack_ids) -> list[str]:
    """Все ключевые слова выбранных тем, без повторов."""
    words: list[str] = []
    for pack_id in pack_ids:
        entry = TOPIC_PACKS.get(pack_id)
        if entry:
            words.extend(w for w in entry[1] if w not in words)
    return words


def pack_search_terms(pack_ids) -> list[str]:
    """Слова, с которыми имеет смысл идти в поиск kwork."""
    terms: list[str] = []
    for pack_id in pack_ids:
        entry = TOPIC_PACKS.get(pack_id)
        if entry:
            terms.extend(t for t in entry[2] if t not in terms)
    return terms
