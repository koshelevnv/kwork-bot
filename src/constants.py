def update_categories(new_cats: dict[str, list[tuple[str, str]]]) -> None:
    """Обновляет KWORK_CATEGORIES и CATEGORY_NAME_BY_ID на месте (in-place)."""
    KWORK_CATEGORIES.clear()
    KWORK_CATEGORIES.update(new_cats)
    CATEGORY_NAME_BY_ID.clear()
    CATEGORY_NAME_BY_ID.update({
        cat_id: name
        for cats in KWORK_CATEGORIES.values()
        for cat_id, name in cats
    })


# ── Подрубрики ─────────────────────────────────────────────────────────────
# Третий уровень kwork. У биржи это «атрибуты» категории, в запросе к ленте
# им соответствует form-поле attr; за один запрос принимается ровно одно
# значение, поэтому каждая выбранная подрубрика стоит отдельного запроса.
# Заказ в выдаче свою подрубрику не сообщает — определить её постфактум,
# как раздел через own_category_id, нельзя.

# Плоский справочник attr_id -> name и attr_id -> category_id
ATTRIBUTE_NAME_BY_ID: dict[str, str] = {
    attr_id: name
    for attrs in KWORK_ATTRIBUTES.values()
    for attr_id, name in attrs
}
ATTRIBUTE_PARENT_BY_ID: dict[str, str] = {
    attr_id: cat_id
    for cat_id, attrs in KWORK_ATTRIBUTES.items()
    for attr_id, _ in attrs
}

# Подрубрика живёт в тех же полях, что и категория (user_categories.category_id,
# order_history.category_id), поэтому её id помечается префиксом: нумерации
# категорий и атрибутов у kwork разные и вполне могут пересечься.
ATTR_PREFIX = "a"


def attr_source(attr_id: str) -> str:
    """id подрубрики → идентификатор источника для БД и монитора."""
    return f"{ATTR_PREFIX}{attr_id}"


def attr_id_of(source: str) -> str | None:
    """Идентификатор источника → id подрубрики, либо None для обычной категории."""
    if source.startswith(ATTR_PREFIX) and source[len(ATTR_PREFIX):].isdigit():
        return source[len(ATTR_PREFIX):]
    return None


def attr_full_name(attr_id: str) -> str:
    """«Категория → Подрубрика» — так подрубрика подписывается в списках и заказах."""
    name = ATTRIBUTE_NAME_BY_ID.get(attr_id, f"Подрубрика {attr_id}")
    cat_id = ATTRIBUTE_PARENT_BY_ID.get(attr_id, "")
    cat_name = CATEGORY_NAME_BY_ID.get(cat_id)
    return f"{cat_name} → {name}" if cat_name else name


def category_group(cat_id: str) -> str | None:
    """Раздел, в котором лежит категория."""
    return next(
        (g for g, cats in KWORK_CATEGORIES.items() if any(c[0] == cat_id for c in cats)),
        None,
    )


def update_attributes(new_attrs: dict[str, list[tuple[str, str]]]) -> None:
    """Обновляет KWORK_ATTRIBUTES и плоские справочники на месте (in-place)."""
    KWORK_ATTRIBUTES.clear()
    KWORK_ATTRIBUTES.update(new_attrs)
    ATTRIBUTE_NAME_BY_ID.clear()
    ATTRIBUTE_NAME_BY_ID.update({
        attr_id: name
        for attrs in KWORK_ATTRIBUTES.values()
        for attr_id, name in attrs
    })
    ATTRIBUTE_PARENT_BY_ID.clear()
    ATTRIBUTE_PARENT_BY_ID.update({
        attr_id: cat_id
        for cat_id, attrs in KWORK_ATTRIBUTES.items()
        for attr_id, _ in attrs
    })

